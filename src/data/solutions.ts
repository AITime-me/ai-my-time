export const solutions: SolutionScenario[] = SOLUTION_SLUGS.map((slug) => {
  const item = solutionsByDefinition.find((solution) => solution.slug === slug);
  if (!item) throw new Error(`Missing solution definition for slug: ${slug}`);
  return item;
});

const solutionsBySlug = Object.fromEntries(solutions.map((item) => [item.slug, item])) as Record<
  SolutionSlug,
  SolutionScenario
>;

export function isSolutionSlug(value: string): value is SolutionSlug {
  return (SOLUTION_SLUGS as readonly string[]).includes(value);
}

export function getSolutionBySlug(slug: string): SolutionScenario | undefined {
  if (!isSolutionSlug(slug)) return undefined;
  return solutionsBySlug[slug];
}

export function getOtherSolutions(slug: string): SolutionScenario[] {
  return solutions.filter((item) => item.slug !== slug);
}
