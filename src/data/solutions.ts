function screens(
  folder: string,
  items: Array<{ alt: string; caption: string; label?: string }>,
  ext: "png" | "jpg" = "png",
): SolutionStep[] {
  return items.map((item, index) => ({
    src: `/solutions/${folder}/${String(index + 1).padStart(2, "0")}.${ext}`,
    alt: item.alt,
    label: item.label,
    caption: item.caption,
  }));
}

